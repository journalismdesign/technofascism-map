<div class="wp-block-column jd-band__body" style="flex-basis:75%"><!-- wp:heading -->
<h2 class="wp-block-heading">La technologie n’est pas <em>une stratégie.</em></h2>
<!-- /wp:heading -->

<!-- wp:columns {"align":"wide","className":"jd-inner"} -->
<div class="wp-block-columns alignwide jd-inner"><!-- wp:column {"width":"45%"} -->
<div class="wp-block-column" style="flex-basis:45%"><!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Les organisations adoptent des outils numériques et des systèmes d’IA plus vite qu’elles ne fixent les règles de leur usage.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Microsoft, Google, Adobe, OpenAI, Anthropic, Notion, Salesforce et des services plus spécialisés prennent en charge des fonctions de plus en plus critiques. Chaque abonnement déplace un peu de contrôle sur les données, les formats et les prix vers des entreprises dont les intérêts ne coïncident pas forcément avec ceux de leurs clients.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Cette dépendance a un coût économique : abonnements récurrents, outils en doublon, contrats qui s’empilent, workflows inefficaces, migrations coûteuses, compétences internes qui s’érodent, erreurs de l’IA qu’il faut corriger.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Elle pèse aussi hors du budget. Les grands modèles consomment de l’énergie, de l’eau et du matériel, et ils modifient le travail de celles et ceux qui les utilisent.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column -->

<!-- wp:column {"width":"55%"} -->
<div class="wp-block-column" style="flex-basis:55%"><!-- wp:paragraph -->
<p>La question n’est donc plus :</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"is-style-question jd-strike"} -->
<p class="is-style-question jd-strike">« Quel outil choisir ? »</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Mais :</p>
<!-- /wp:paragraph -->

<!-- wp:list {"className":"is-style-index jd-questions"} -->
<ul class="wp-block-list is-style-index jd-questions"><!-- wp:list-item -->
<li>À quoi doit-il réellement servir ?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Quelles données peut-on lui confier ?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>De quoi nous rend-il dépendants ?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Pourrons-nous encore travailler sans lui demain ?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Existe-t-il une alternative plus maîtrisable ?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Que voulons-nous automatiser — et que voulons-nous préserver ?</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Nous aidons les organisations à y répondre avant que les choix techniques ne deviennent des dépendances structurelles, en cherchant l’équilibre entre efficacité, autonomie et responsabilité.</p>
