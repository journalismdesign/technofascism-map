<!-- wp:group {"className":"jd-faq","layout":{"type":"default"}} -->
<div class="wp-block-group jd-faq"><!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>À qui s’adressent vos formations ?</summary><!-- wp:paragraph -->
<p>Aux médias et aux organisations dont le travail repose sur l’information et les contenus, des directions aux équipes opérationnelles, quel que soit leur niveau technique.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Chaque programme est construit sur mesure, à partir de vos métiers et de la maturité de vos équipes sur ces sujets.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Quelle est la différence entre formation et conseil ?</summary><!-- wp:paragraph -->
<p>La formation fait monter les équipes en compétences : comprendre l’IA, pratiquer les outils, savoir ce qu’on peut leur confier. Le conseil porte sur les choix de l’organisation : diagnostic, prototypes, doctrine, gouvernance, réduction des dépendances.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Les deux se complètent souvent, et les parcours peuvent articuler les deux. <a href="<?php echo jd_url( '', 'expertises' ); ?>">Voir les trois étapes de l’accompagnement →</a></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Qui sont les formateurs ?</summary><!-- wp:paragraph -->
<p>Gérald Holubowicz, fondateur du studio, intervient en personne. Il forme depuis plus de quinze ans journalistes, étudiants et professionnels aux transformations de l’information et du numérique.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Selon les sujets, il peut s’associer à d’autres professionnels du réseau du studio.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Combien de temps dure une formation ?</summary><!-- wp:paragraph -->
<p>Cela dépend du besoin : une conférence, un atelier, une journée ou un parcours en plusieurs sessions. Chaque intervention est calibrée selon vos objectifs et votre rythme.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Sur quels outils travaillez-vous ?</summary><!-- wp:paragraph -->
<p>Sur ceux que vos équipes utilisent déjà, et sur des alternatives européennes, libres ou open source lorsque c’est pertinent. Aucun éditeur ne nous rémunère : nous ne vendons pas de licence.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Faut-il partager des données de l’organisation pendant la formation ?</summary><!-- wp:paragraph -->
<p>Non. Les exercices s’appuient sur des documents choisis avec vous, sans donnée sensible. Savoir ce que l’on peut confier ou non aux outils d’IA fait d’ailleurs partie de la formation.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>D’où viennent les contenus ?</summary><!-- wp:paragraph -->
<p>Du terrain. Les outils et les usages abordés sont testés dans la production de SYNTH, le média édité par le studio, et dans les missions menées auprès des médias et des organisations.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Que se passe-t-il après la formation ?</summary><!-- wp:paragraph -->
<p>Si l’organisation le souhaite, la formation peut déboucher sur une journée de diagnostic, un prototype ou l’écriture d’une doctrine IA. Ce n’est jamais une condition.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"jd-faq__item"} -->
<details class="wp-block-details jd-faq__item"><summary>Combien coûte une formation ?</summary><!-- wp:paragraph -->
<p>Les formations et parcours collectifs sont proposés sur devis, selon le format, la durée et le nombre de participants.</p>
<!-- /wp:paragraph --></details>
